async function main() {
  const doApply = process.argv.includes('--apply');
  const force = process.argv.includes('--force');

  // 1. 데이터 검증: dayNumber 부여 (정확히 30일 × 40개 = 1,200개로 맞춤)
  const WORDS_PER_DAY = 40;
  const TOTAL_DAYS = 30;
  const TOTAL_WORDS = WORDS_PER_DAY * TOTAL_DAYS; // 1200

  // VOCAB_DATA를 정확히 1,200개로 자름
  const trimmedData = VOCAB_DATA.slice(0, TOTAL_WORDS);

  const words = [];
  for (let i = 0; i < trimmedData.length; i++) {
    const day = Math.floor(i / WORDS_PER_DAY) + 1;
    const [english, korean, chinese] = trimmedData[i];
    words.push({
      english,
      korean,
      chinese,
      definition: '',
      synonyms: '',
      dayNumber: day,
    });
  }

  const dayCount = TOTAL_DAYS; // 30
  const days = Array.from({ length: dayCount }, (_, i) => ({
    id: i + 1,
    name: `DAY ${i + 1}`,
  }));

  console.log(`\n=== vol.5 junior 단어 데이터 생성 ===`);
  console.log(`총 단어 수: ${words.length} (원본 ${VOCAB_DATA.length} → 잘라서 ${words.length})`);
  console.log(`총 DAY 수: ${dayCount}`);
  console.log(`DAY 1 단어 수: ${words.filter(w => w.dayNumber === 1).length}`);
  console.log(`DAY 30 단어 수: ${words.filter(w => w.dayNumber === 30).length}`);
  console.log(`샘플(DAY 1 첫 3개):`);
  words.filter(w => w.dayNumber === 1).slice(0, 3).forEach((w, i) => {
    console.log(`  ${i + 1}. ${w.english} / ${w.korean} / ${w.chinese}`);
  });

  if (!doApply) {
    console.log(`\n(드라이런) 실제 저장하려면: node scripts/seed-junior-vocabulary.cjs --apply`);
    return;
  }

  // 2. 기존 데이터 확인
  console.log(`\n=== Supabase 저장 시작 ===`);
  const { data: existingWords } = await supabase
    .from(TABLE)
    .select('key,value')
    .eq('key', 'vocabulary_words_junior')
    .single();

  if (existingWords && Array.isArray(existingWords.value) && existingWords.value.length > 0 && !force) {
    console.log(`⚠️  vocabulary_words_junior 이미 존재함 (${existingWords.value.length}개)`);
    console.log(`   강제 덮어쓰기: --force 추가`);
    return;
  }

  // 3. 단어 저장
  const { error: wordsErr } = await supabase
    .from(TABLE)
    .upsert({ key: 'vocabulary_words_junior', value: words });
  if (wordsErr) {
    console.error(`❌ 단어 저장 실패:`, wordsErr.message);
    process.exit(1);
  }
  console.log(`✅ vocabulary_words_junior 저장 완료 (${words.length}개)`);

  // 4. DAY 저장
  const { error: daysErr } = await supabase
    .from(TABLE)
    .upsert({ key: 'vocabulary_days_junior', value: days });
  if (daysErr) {
    console.error(`❌ DAY 저장 실패:`, daysErr.message);
    process.exit(1);
  }
  console.log(`✅ vocabulary_days_junior 저장 완료 (${dayCount}개 DAY)`);

  // 5. 검증
  const { data: verify } = await supabase
    .from(TABLE)
    .select('value')
    .eq('key', 'vocabulary_words_junior')
    .single();
  console.log(`\n=== 검증 ===`);
  console.log(`저장된 단어 수: ${Array.isArray(verify?.value) ? verify.value.length : 0}`);
  console.log(`완료.`);
}

main().catch(e => { console.error('❌ 오류:', e.message); process.exit(1); });
